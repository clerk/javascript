export function hasCountryFlag(iso: string): boolean {
  return supportedCountryFlags.has(iso.toLowerCase());
}

export function CountryFlag({ iso, ...props }: CountryFlagProps) {
  const normalizedIso = iso.toLowerCase();
  const Group = countryFlagGroups.get(normalizedIso[0] ?? '');
  if (!Group || !supportedCountryFlags.has(normalizedIso)) {
    return <Globe {...props} />;
  }
  return (
    <React.Suspense fallback={<Globe {...props} />}>
      <Group
        iso={normalizedIso}
        {...props}
      />
    </React.Suspense>
  );
}
