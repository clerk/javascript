import ts from 'typescript';

import {
  nativeListedKinds,
  nativeResourceExclusions,
  nativeResourceRoutes,
  nativeUserCollections,
} from '../../src/internal/clerk-js/nativeResourceRoutes';
import type { GeneratedSwiftFile } from './model';
import { findDeclaredType } from './type-system';

/** Inherited reload alone does not make a snapshot an independently callable resource. */
export function callableResources(program: ts.Program): Map<string, string[]> {
  const checker = program.getTypeChecker();
  const resources = new Map<string, string[]>();
  for (const file of program.getSourceFiles()) {
    if (!file.fileName.includes('/src/types/') || file.isDeclarationFile) {
      continue;
    }
    for (const declaration of file.statements) {
      if (
        !(ts.isInterfaceDeclaration(declaration) || ts.isTypeAliasDeclaration(declaration)) ||
        !declaration.name.text.endsWith('Resource')
      ) {
        continue;
      }
      const methods = checker
        .getPropertiesOfType(checker.getTypeAtLocation(declaration))
        .filter(symbol => {
          if (symbol.name === 'reload' || symbol.name.startsWith('__')) {
            return false;
          }
          const node = symbol.valueDeclaration ?? symbol.declarations?.[0];
          return (
            node &&
            checker.getNonNullableType(checker.getTypeOfSymbolAtLocation(symbol, node)).getCallSignatures().length
          );
        })
        .map(symbol => symbol.name);
      if (methods.length) {
        resources.set(declaration.name.text, methods);
      }
    }
  }
  return resources;
}

export function validateNativeResourceRoutes(program: ts.Program, methodRoots: readonly string[]): void {
  const classified = { ...nativeResourceRoutes, ...nativeResourceExclusions };
  for (const [name, methods] of callableResources(program)) {
    if (!Object.hasOwn(classified, name)) {
      throw new Error(`Native resource ${name} needs a route or an exclusion: ${methods.join(', ')}`);
    }
  }
  for (const name of Object.keys(classified)) {
    findDeclaredType(program, name);
  }
  for (const name of methodRoots) {
    if (!Object.hasOwn(nativeResourceRoutes, name)) {
      throw new Error(`Swift method root ${name} has no native resource route`);
    }
  }
}

export function emitReceiverKinds(): GeneratedSwiftFile {
  const emitEnum = (name: string, cases: readonly string[]) =>
    `  public enum ${name}: String, Sendable, Encodable {\n${cases.map(value => `    case ${value}`).join('\n')}\n  }`;
  return {
    filename: 'methods/ClerkJSReceiverKinds.swift',
    contents: `// Generated by packages/shared/scripts/generate-swift-models.ts. Do not edit.
// Source: nativeResourceRoutes in @clerk/shared/internal/clerk-js/nativeResourceRoutes.

extension ClerkJSReceiver {
${emitEnum('UserCollection', nativeUserCollections)}

${emitEnum('ListedKind', nativeListedKinds)}
}
`,
  };
}
