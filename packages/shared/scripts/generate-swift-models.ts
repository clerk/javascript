function isTypeFlag(type: ts.Type, flag: ts.TypeFlags): boolean {
  return (type.flags & flag) !== 0;
}

function objectFlags(type: ts.Type): ts.ObjectFlags {
  return 'objectFlags' in type ? ((type as ts.ObjectType).objectFlags ?? 0) : 0;
}

function declaredName(type: ts.Type): string | undefined {
  const name = type.aliasSymbol?.getName() ?? type.getSymbol()?.getName();
  if (!name || name.startsWith('__')) {
    return undefined;
  }
  return name;
}

function shouldSkipNamedType(name: string): boolean {
  return SKIP_NAME.test(name) || DOM_NAMES.has(name);
}

function isSkippedUiName(name: string): boolean {
  return /appearance|ClerkUI|^ClerkOptions$/.test(name);
}

function isUtilityName(name: string): boolean {
  return /^(Partial|Pick|Omit|Required|Readonly|Record|Extract|Exclude|NonNullable|ReturnType|Awaited)$/.test(name);
}

function shouldSkipMethodName(name: string): boolean {
  if (name.startsWith('__')) {
    return true;
  }
  if (/^(mount|unmount|open|close|redirect)/.test(name)) {
    return true;
  }
  if (/redirect/i.test(name)) {
    return true;
  }
  if (isSkippedUiName(name)) {
    return true;
  }
  if (/Web3|Metamask|CoinbaseWallet|OKXWallet|Solana|authenticateWithBase$/.test(name)) {
    return true;
  }
  if (/WithPopup$/.test(name)) {
    return true;
  }
  return false;
}

function methodOwnerName(tsName: string): string {
  if (tsName === 'HeadlessBrowserClerk' || tsName === 'Clerk') {
    return 'Clerk';
  }
  return tsName.replace(/Resource$/, '');
}

function asExistingModel(ctx: Ctx, name: string): string | undefined {
  const candidates = [
    name,
    stripJsonSuffix(name),
    name.replace(/Resource$/, ''),
    stripJsonSuffix(name.replace(/Resource$/, '')),
  ];
  for (const candidate of candidates) {
    if (ctx.modelNames.has(candidate)) {
      return candidate;
    }
  }
  return undefined;
}

function stripJsonSuffix(name: string): string {
  return name.endsWith('JSON') ? name.slice(0, -4) : name;
}

function snakeToCamel(value: string): string {
  return value.replace(/[_-]([a-zA-Z0-9])/g, (_, char: string) => char.toUpperCase());
}

function pascalCase(value: string): string {
  const camel = snakeToCamel(value);
  return camel ? camel[0].toUpperCase() + camel.slice(1) : value;
}

function swiftIdent(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_]/g, '');
  const base = cleaned.length === 0 ? 'value' : /^[0-9]/.test(cleaned) ? `n${cleaned}` : cleaned;
  return SWIFT_KEYWORDS.has(base) ? `\`${base}\`` : base;
}

function swiftCaseName(raw: string): string {
  const camel = snakeToCamel(raw.replace(/[^a-zA-Z0-9]+/g, '_'));
  const ident = camel.length === 0 ? 'value' : camel[0].toLowerCase() + camel.slice(1);
  if (ident === 'unknown') {
    return 'unknownValue';
  }
  return swiftIdent(ident);
}

function isNullish(type: ts.Type): boolean {
  return (
    isTypeFlag(type, ts.TypeFlags.Null) ||
    isTypeFlag(type, ts.TypeFlags.Undefined) ||
    isTypeFlag(type, ts.TypeFlags.Void) ||
    isTypeFlag(type, ts.TypeFlags.VoidLike)
  );
}

function isNever(type: ts.Type): boolean {
  return isTypeFlag(type, ts.TypeFlags.Never);
}

function isAnyLike(type: ts.Type): boolean {
  return isTypeFlag(type, ts.TypeFlags.Any) || isTypeFlag(type, ts.TypeFlags.Unknown);
}

function isBooleanType(type: ts.Type): boolean {
  return isTypeFlag(type, ts.TypeFlags.Boolean) || isTypeFlag(type, ts.TypeFlags.BooleanLiteral);
}

function isNumberType(type: ts.Type): boolean {
  return isTypeFlag(type, ts.TypeFlags.Number) || isTypeFlag(type, ts.TypeFlags.NumberLiteral);
}

function isWideString(type: ts.Type): boolean {
  return (
    isTypeFlag(type, ts.TypeFlags.String) ||
    isTypeFlag(type, ts.TypeFlags.TemplateLiteral) ||
    isTypeFlag(type, ts.TypeFlags.StringMapping)
  );
}

function isStringy(type: ts.Type): boolean {
  return type.isStringLiteral() || isWideString(type);
}

function isObjectish(type: ts.Type): boolean {
  if (isPrimitiveNonEnum(type) || type.isStringLiteral() || isAnyLike(type) || isNever(type) || isNullish(type)) {
    return false;
  }
  if (isTypeFlag(type, ts.TypeFlags.Object) || type.isClassOrInterface()) {
    return true;
  }
  return type.getProperties().length > 0 || Boolean(type.getStringIndexType());
}

function decomposeUnion(type: ts.Type): { parts: ts.Type[]; optional: boolean } {
  if (!type.isUnion()) {
    return { parts: [type], optional: false };
  }
  let optional = false;
  const parts: ts.Type[] = [];
  for (const part of type.types) {
    if (isNullish(part)) {
      optional = true;
      continue;
    }
    if (isNever(part)) {
      continue;
    }
    parts.push(part);
  }
  return { parts, optional };
}

function uniqueTypes(parts: ts.Type[], checker: ts.TypeChecker): ts.Type[] {
  const seen = new Set<string>();
  const out: ts.Type[] = [];
  for (const part of parts) {
    const key = checker.typeToString(part);
    if (seen.has(key)) {
      continue;
    }
    seen.add(key);
    out.push(part);
  }
  return out;
}

function isArrayType(checker: ts.TypeChecker, type: ts.Type): ts.Type | undefined {
  if (checker.isArrayType(type)) {
    const args = checker.getTypeArguments(type as ts.TypeReference);
    return args[0];
  }
  const name = type.aliasSymbol?.getName() ?? type.getSymbol()?.getName();
  if (name === 'Array' || name === 'ReadonlyArray' || name === 'Readonly') {
    const args = checker.getTypeArguments(type as ts.TypeReference);
    if (name === 'Readonly' && args[0]) {
      return isArrayType(checker, args[0]);
    }
    return args[0];
  }
  return undefined;
}

function tupleElements(checker: ts.TypeChecker, type: ts.Type): ts.Type[] | undefined {
  if (checker.isTupleType(type)) {
    return [...checker.getTypeArguments(type as ts.TypeReference)];
  }
  if ((objectFlags(type) & ts.ObjectFlags.Tuple) !== 0) {
    return [...checker.getTypeArguments(type as ts.TypeReference)];
  }
  return undefined;
}

function isFunctionType(checker: ts.TypeChecker, type: ts.Type): boolean {
  return checker.getSignaturesOfType(type, ts.SignatureKind.Call).length > 0 && type.getProperties().length === 0;
}

function isDomType(type: ts.Type): boolean {
  const name = declaredName(type);
  if (name && DOM_NAMES.has(name)) {
    return true;
  }
  const symbol = type.getSymbol();
  const file = symbol?.declarations?.[0]?.getSourceFile().fileName ?? '';
  return file.includes('lib.dom.d.ts');
}

function typeProperties(
  checker: ts.TypeChecker,
  type: ts.Type,
): { symbol: ts.Symbol; type: ts.Type; optional: boolean }[] {
  const seen = new Set<string>();
  const out: { symbol: ts.Symbol; type: ts.Type; optional: boolean }[] = [];
  for (const symbol of type.getProperties()) {
    const name = symbol.getName();
    if (seen.has(name) || name.startsWith('__')) {
      continue;
    }
    seen.add(name);
    const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0];
    const propType = declaration
      ? checker.getTypeOfSymbolAtLocation(symbol, declaration)
      : checker.getTypeOfSymbol(symbol);
    const optional = (symbol.flags & ts.SymbolFlags.Optional) !== 0;
    out.push({ symbol, type: propType, optional });
  }
  return out;
}

function findDeclaredType(program: ts.Program, name: string): ts.Type {
  const checker = program.getTypeChecker();
  for (const sourceFile of program.getSourceFiles()) {
    if (sourceFile.isDeclarationFile || sourceFile.fileName.includes('node_modules')) {
      continue;
    }
    for (const statement of sourceFile.statements) {
      if (
        (ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement)) &&
        statement.name.text === name &&
        hasExportModifier(statement)
      ) {
        return checker.getTypeAtLocation(statement.name);
      }
    }
  }
  throw new Error(`Could not find exported type ${name}`);
}

function hasExportModifier(statement: ts.InterfaceDeclaration | ts.TypeAliasDeclaration): boolean {
  return Boolean(statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword));
}

export function createSharedProgram(): ts.Program {
  const configPath = path.join(sharedPackageRoot(), 'tsconfig.json');
  const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
  if (configFile.error) {
    throw new Error(ts.flattenDiagnosticMessageText(configFile.error.messageText, '\n'));
  }
  const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, sharedPackageRoot());
  return ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options });
}

function typeId(checker: ts.TypeChecker, type: ts.Type): string {
  const name = declaredName(type);
  if (name) {
    const declaration = type.aliasSymbol?.declarations?.[0] ?? type.getSymbol()?.declarations?.[0];
    const file = declaration?.getSourceFile().fileName ?? '';
    return `named:${file}:${name}`;
  }
  const { parts } = decomposeUnion(type);
  const unique = uniqueTypes(parts, checker);
  if (allStringLiterals(unique)) {
    return `enum:${unique
      .map(part => part.value)
      .slice()
      .sort()
      .join('|')}`;
  }
  const props = typeProperties(checker, type)
    .map(prop => `${prop.symbol.getName()}:${checker.typeToString(prop.type)}:${prop.optional ? '?' : ''}`)
    .sort()
    .join(';');
  const index = type.getStringIndexType();
  return `anon:${props}|i:${index ? checker.typeToString(index) : ''}`;
}

function claimName(ctx: Ctx, preferred: string): string {
  let name = preferred;
  let suffix = 2;
  while (ctx.usedNames.has(name) || ctx.decls.has(name)) {
    name = `${preferred}${suffix}`;
    suffix += 1;
  }
  ctx.usedNames.add(name);
  return name;
}

function internName(ctx: Ctx, id: string, preferred: string): string {
  const existing = ctx.typeIds.get(id);
  if (existing) {
    return existing;
  }
  const swiftName = claimName(ctx, stripJsonSuffix(preferred));
  ctx.typeIds.set(id, swiftName);
  return swiftName;
}

function enqueueNamed(ctx: Ctx, name: string, type: ts.Type): string {
  const mapped = asExistingModel(ctx, name);
  if (mapped) {
    return mapped;
  }
  const id = typeId(ctx.checker, type);
  const existing = ctx.typeIds.get(id);
  if (existing) {
    return existing;
  }
  const swiftName = internName(ctx, id, name);
  if (!ctx.decls.has(swiftName) && !ctx.queued.has(swiftName)) {
    ctx.queued.set(swiftName, type);
  }
  return swiftName;
}

function optionalize(ref: SwiftRef): SwiftRef {
  if (ref.kind === 'optional') {
    return ref;
  }
  return { kind: 'optional', of: ref };
}

function allStringLiterals(parts: ts.Type[]): parts is (ts.Type & { value: string })[] {
  return parts.length >= 2 && parts.every(part => part.isStringLiteral());
}

function isIndexOnly(ctx: Ctx, type: ts.Type): boolean {
  const usable = typeProperties(ctx.checker, type).filter(prop => {
    const { parts } = decomposeUnion(prop.type);
    return parts.length > 0 && !parts.every(isNever);
  });
  return usable.length === 0 && Boolean(type.getStringIndexType());
}

function isPrimitiveNonEnum(type: ts.Type): boolean {
  return isAnyLike(type) || isBooleanType(type) || isNumberType(type) || isStringy(type);
}

function resolveRef(ctx: Ctx, type: ts.Type, hint: string, wireName?: string): SwiftRef {
  if (isNever(type) || isDomType(type) || isFunctionType(ctx.checker, type)) {
    return { kind: 'primitive', name: 'JSONValue' };
  }

  const { parts, optional } = decomposeUnion(type);
  const unique = uniqueTypes(parts, ctx.checker);
  const name = declaredName(type);
  const existing = name ? asExistingModel(ctx, name) : undefined;
  if (existing) {
    const ref: SwiftRef = { kind: 'named', name: existing };
    return optional ? optionalize(ref) : ref;
  }
  if (name && isSkippedUiName(name)) {
    return optional ? optionalize({ kind: 'primitive', name: 'JSONValue' }) : { kind: 'primitive', name: 'JSONValue' };
  }
  if (name && shouldSkipNamedType(name) && ctx.modelNames.size > 0) {
    return optional ? optionalize({ kind: 'primitive', name: 'JSONValue' }) : { kind: 'primitive', name: 'JSONValue' };
  }

  if (name && !isUtilityName(name) && !shouldSkipNamedType(name) && name !== 'Array' && name !== 'ReadonlyArray') {
    if (isIndexOnly(ctx, type)) {
      const inner = resolveSingle(ctx, type, hint, wireName);
      return optional ? optionalize(inner) : inner;
    }
    if (unique.length === 1 && isPrimitiveNonEnum(unique[0])) {
      const inner = resolveSingle(ctx, unique[0], hint, wireName);
      return optional ? optionalize(inner) : inner;
    }
    if (unique.length > 1 && unique.every(isStringy) && !allStringLiterals(unique)) {
      return optional ? optionalize({ kind: 'primitive', name: 'String' }) : { kind: 'primitive', name: 'String' };
    }
    if (
      unique.length > 1 &&
      !allStringLiterals(unique) &&
      !unique.every(part => isObjectish(part) && !isArrayType(ctx.checker, part))
    ) {
      return optional
        ? optionalize({ kind: 'primitive', name: 'JSONValue' })
        : { kind: 'primitive', name: 'JSONValue' };
    }
    const ref: SwiftRef = { kind: 'named', name: enqueueNamed(ctx, name, type) };
    return optional ? optionalize(ref) : ref;
  }

  const inner = resolveUnionParts(ctx, unique, hint, wireName);
  return optional ? optionalize(inner) : inner;
}

function resolveUnionParts(ctx: Ctx, parts: ts.Type[], hint: string, wireName?: string): SwiftRef {
  if (parts.length === 0) {
    return { kind: 'primitive', name: 'JSONValue' };
  }
  if (parts.length === 1) {
    return resolveSingle(ctx, parts[0], hint, wireName);
  }
  if (allStringLiterals(parts)) {
    const name = enqueueEnum(
      ctx,
      hint,
      parts.map(part => part.value),
    );
    return { kind: 'named', name };
  }
  if (parts.every(isStringy)) {
    return { kind: 'primitive', name: 'String' };
  }
  if (parts.every(isBooleanType)) {
    return { kind: 'primitive', name: 'Bool' };
  }
  if (parts.every(isNumberType)) {
    return dateOrInt(wireName);
  }
  if (parts.every(part => isObjectish(part) && !isArrayType(ctx.checker, part))) {
    const mapped = parts.map(part => {
      const partName = declaredName(part);
      return partName ? asExistingModel(ctx, partName) : undefined;
    });
    if (mapped.every(name => Boolean(name)) && new Set(mapped).size > 1) {
      return { kind: 'primitive', name: 'JSONValue' };
    }
    return { kind: 'named', name: enqueueObjectUnion(ctx, hint, parts) };
  }
  return { kind: 'primitive', name: 'JSONValue' };
}

function dateOrInt(wireName?: string): SwiftRef {
  if (wireName && /_at$/.test(wireName)) {
    return { kind: 'primitive', name: 'Date' };
  }
  return { kind: 'primitive', name: 'Int' };
}

function isBuiltInDate(type: ts.Type): boolean {
  const name = declaredName(type) ?? type.getSymbol()?.getName();
  return name === 'Date';
}

function isOpaqueLibType(type: ts.Type): boolean {
  const name = declaredName(type) ?? type.getSymbol()?.getName();
  return (
    name === 'Blob' ||
    name === 'File' ||
    name === 'URL' ||
    name === 'URLSearchParams' ||
    name === 'RegExp' ||
    name === 'ArrayBuffer' ||
    name === 'FormData'
  );
}

function resolveSingle(ctx: Ctx, type: ts.Type, hint: string, wireName?: string): SwiftRef {
  if (isAnyLike(type)) {
    return { kind: 'primitive', name: 'JSONValue' };
  }
  if (isBuiltInDate(type)) {
    return { kind: 'primitive', name: 'Date' };
  }
  if (isOpaqueLibType(type)) {
    return { kind: 'primitive', name: 'JSONValue' };
  }
  if (isBooleanType(type)) {
    return { kind: 'primitive', name: 'Bool' };
  }
  if (isNumberType(type)) {
    return dateOrInt(wireName);
  }
  if (type.isStringLiteral()) {
    return { kind: 'primitive', name: 'String' };
  }
  if (isStringy(type)) {
    return { kind: 'primitive', name: 'String' };
  }

  const element = isArrayType(ctx.checker, type);
  if (element) {
    return { kind: 'array', of: resolveRef(ctx, element, `${hint}Element`) };
  }

  const tuple = tupleElements(ctx.checker, type);
  if (tuple && tuple.length > 0) {
    const first = resolveRef(ctx, tuple[0], `${hint}Element`);
    return { kind: 'array', of: first };
  }

  if (isFunctionType(ctx.checker, type) || isDomType(type)) {
    return { kind: 'primitive', name: 'JSONValue' };
  }

  const props = typeProperties(ctx.checker, type);
  const usableProps = props.filter(prop => !isNever(decomposeUnion(prop.type).parts[0] ?? prop.type));
  const index = type.getStringIndexType();

  if (usableProps.length === 0 && index) {
    if (isAnyLike(index)) {
      return { kind: 'primitive', name: 'JSONValue' };
    }
    const { parts } = decomposeUnion(index);
    if (parts.length > 1 && !allStringLiterals(parts) && !parts.every(isStringy)) {
      return { kind: 'dict', of: { kind: 'primitive', name: 'JSONValue' } };
    }
    return { kind: 'dict', of: resolveRef(ctx, index, `${hint}Value`) };
  }

  if (!isObjectish(type)) {
    return { kind: 'primitive', name: 'JSONValue' };
  }

  const name = declaredName(type);
  const existing = name ? asExistingModel(ctx, name) : undefined;
  if (existing) {
    return { kind: 'named', name: existing };
  }
  if (name && shouldSkipNamedType(name) && ctx.modelNames.size > 0) {
    return { kind: 'primitive', name: 'JSONValue' };
  }
  if (name && !isUtilityName(name) && !shouldSkipNamedType(name) && name !== 'Array') {
    return { kind: 'named', name: enqueueNamed(ctx, name, type) };
  }

  return { kind: 'named', name: enqueueNamed(ctx, hint, type) };
}

function enqueueEnum(ctx: Ctx, hint: string, values: string[]): string {
  const id = `enum:${[...values].sort().join('|')}`;
  const existing = ctx.typeIds.get(id);
  if (existing) {
    return existing;
  }
  const name = internName(ctx, id, hint);
  const usedCases = new Set<string>(['unknown']);
  const cases = values.map(raw => {
    let caseName = swiftCaseName(raw);
    let suffix = 2;
    while (usedCases.has(caseName.replace(/`/g, ''))) {
      caseName = `${swiftCaseName(raw)}${suffix}`;
      suffix += 1;
    }
    usedCases.add(caseName.replace(/`/g, ''));
    return { name: caseName, raw };
  });
  ctx.decls.set(name, { kind: 'enum', name, cases });
  return name;
}

function enqueueObjectUnion(ctx: Ctx, hint: string, parts: ts.Type[]): string {
  const id = `union:${parts
    .map(part => typeId(ctx.checker, part))
    .sort()
    .join('+')}`;
  const existing = ctx.typeIds.get(id);
  if (existing) {
    return existing;
  }
  const name = internName(ctx, id, hint);
  if (!ctx.decls.has(name)) {
    ctx.decls.set(name, structFromMergedUnion(ctx, name, parts));
  }
  return name;
}

function structFromType(ctx: Ctx, name: string, type: ts.Type): SwiftStruct {
  const properties: SwiftProperty[] = [];
  for (const prop of typeProperties(ctx.checker, type)) {
    const wireName = prop.symbol.getName();
    if (isSkippedUiName(wireName) || typeHasFunction(ctx.checker, prop.type)) {
      continue;
    }
    const { parts, optional } = decomposeUnion(prop.type);
    const unique = uniqueTypes(parts, ctx.checker);
    if (unique.length === 0 || unique.every(isNever)) {
      continue;
    }
    const hint = `${name}${pascalCase(wireName)}`;
    let ref = resolveUnionParts(ctx, unique, hint, wireName);
    if (optional || prop.optional) {
      ref = optionalize(ref);
    }
    properties.push({
      name: swiftIdent(snakeToCamel(wireName)),
      wireName,
      type: ref,
      isDate: isDateRef(ref),
    });
  }
  const id = properties.find(property => property.wireName === 'id' && !isOptionalRef(property.type));
  const identifiable = Boolean(id && emitRef(id.type) === 'String');
  return { kind: 'struct', name, properties, identifiable };
}

function isOptionalRef(ref: SwiftRef): boolean {
  return ref.kind === 'optional';
}

function isDateRef(ref: SwiftRef): boolean {
  if (ref.kind === 'optional') {
    return isDateRef(ref.of);
  }
  return ref.kind === 'primitive' && ref.name === 'Date';
}

function drainQueue(ctx: Ctx): void {
  while (ctx.queued.size > 0) {
    const [name, type] = ctx.queued.entries().next().value as [string, ts.Type];
    ctx.queued.delete(name);
    if (ctx.decls.has(name) || shouldSkipNamedType(name)) {
      continue;
    }
    const { parts } = decomposeUnion(type);
    const unique = uniqueTypes(parts, ctx.checker);
    if (allStringLiterals(unique)) {
      ctx.typeIds.set(
        `enum:${unique
          .map(part => part.value)
          .slice()
          .sort()
          .join('|')}`,
        name,
      );
      const usedCases = new Set<string>(['unknown']);
      const cases = unique.map(part => {
        let caseName = swiftCaseName(part.value);
        let suffix = 2;
        while (usedCases.has(caseName.replace(/`/g, ''))) {
          caseName = `${swiftCaseName(part.value)}${suffix}`;
          suffix += 1;
        }
        usedCases.add(caseName.replace(/`/g, ''));
        return { name: caseName, raw: part.value };
      });
      ctx.decls.set(name, { kind: 'enum', name, cases });
      continue;
    }
    if (unique.length > 1 && unique.every(part => isObjectish(part) && !isArrayType(ctx.checker, part))) {
      ctx.decls.set(name, structFromMergedUnion(ctx, name, unique));
      continue;
    }
    ctx.decls.set(name, structFromType(ctx, name, unique[0] ?? type));
  }
}

function structFromMergedUnion(ctx: Ctx, name: string, parts: ts.Type[]): SwiftStruct {
  const merged = new Map<string, { types: ts.Type[]; optional: boolean }>();
  for (const part of parts) {
    for (const prop of typeProperties(ctx.checker, part)) {
      const current = merged.get(prop.symbol.getName());
      if (current) {
        current.types.push(prop.type);
        current.optional ||= prop.optional || decomposeUnion(prop.type).optional;
      } else {
        merged.set(prop.symbol.getName(), {
          types: [prop.type],
          optional: prop.optional || decomposeUnion(prop.type).optional,
        });
      }
    }
  }
  for (const [wireName, value] of merged) {
    const presentOnAll = parts.every(part =>
      typeProperties(ctx.checker, part).some(prop => prop.symbol.getName() === wireName),
    );
    if (!presentOnAll) {
      value.optional = true;
    }
  }
  const properties: SwiftProperty[] = [];
  for (const [wireName, value] of merged) {
    if (isSkippedUiName(wireName)) {
      continue;
    }
    const hint = `${name}${pascalCase(wireName)}`;
    const resolvedParts = uniqueTypes(
      value.types.flatMap(item => decomposeUnion(item).parts),
      ctx.checker,
    );
    let ref = resolveUnionParts(ctx, resolvedParts, hint, wireName);
    if (value.optional) {
      ref = optionalize(ref);
    }
    properties.push({
      name: swiftIdent(snakeToCamel(wireName)),
      wireName,
      type: ref,
      isDate: isDateRef(ref),
    });
  }
  const id = properties.find(property => property.wireName === 'id' && !isOptionalRef(property.type));
  return {
    kind: 'struct',
    name,
    properties,
    identifiable: Boolean(id && emitRef(id.type) === 'String'),
  };
}

function collectDecls(
  roots: readonly string[] = SWIFT_MODEL_ROOTS,
  program: ts.Program = createSharedProgram(),
): SwiftDecl[] {
  const checker = program.getTypeChecker();
  const ctx: Ctx = {
    checker,
    decls: new Map(),
    queued: new Map(),
    usedNames: new Set(['JSONValue']),
    typeIds: new Map(),
    modelNames: new Set(),
  };
  for (const root of roots) {
    enqueueNamed(ctx, root, findDeclaredType(program, root));
  }
  drainQueue(ctx);
  return [...ctx.decls.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function emitRef(ref: SwiftRef): string {
  switch (ref.kind) {
    case 'named':
      return ref.name;
    case 'optional':
      return `${emitRef(ref.of)}?`;
    case 'array':
      return `[${emitRef(ref.of)}]`;
    case 'dict':
      return `[String: ${emitRef(ref.of)}]`;
    case 'primitive':
      return ref.name;
    default: {
      const _exhaustive: never = ref;
      return _exhaustive;
    }
  }
}

function emitHelperFile(): string {
  return `${GENERATED_HEADER}
import Foundation

public enum JSONValue: Codable, Equatable, Sendable {
  case null
  case bool(Bool)
  case number(Double)
  case string(String)
  case array([JSONValue])
  case object([String: JSONValue])

  public init(from decoder: Decoder) throws {
    let container = try decoder.singleValueContainer()
    if container.decodeNil() {
      self = .null
    } else if let value = try? container.decode(Bool.self) {
      self = .bool(value)
    } else if let value = try? container.decode(Double.self) {
      self = .number(value)
    } else if let value = try? container.decode(String.self) {
      self = .string(value)
    } else if let value = try? container.decode([JSONValue].self) {
      self = .array(value)
    } else if let value = try? container.decode([String: JSONValue].self) {
      self = .object(value)
    } else {
      throw DecodingError.dataCorruptedError(in: container, debugDescription: "Unsupported JSON value")
    }
  }

  public func encode(to encoder: Encoder) throws {
    var container = encoder.singleValueContainer()
    switch self {
    case .null:
      try container.encodeNil()
    case .bool(let value):
      try container.encode(value)
    case .number(let value):
      try container.encode(value)
    case .string(let value):
      try container.encode(value)
    case .array(let value):
      try container.encode(value)
    case .object(let value):
      try container.encode(value)
    }
  }
}

extension KeyedDecodingContainer {
  func decodeMillisecondsDate(forKey key: Key) throws -> Date {
    let millis = try decode(Int64.self, forKey: key)
    return Date(timeIntervalSince1970: TimeInterval(millis) / 1000)
  }

  func decodeIfPresentMillisecondsDate(forKey key: Key) throws -> Date? {
    guard let millis = try decodeIfPresent(Int64.self, forKey: key) else {
      return nil
    }
    return Date(timeIntervalSince1970: TimeInterval(millis) / 1000)
  }
}

extension KeyedEncodingContainer {
  mutating func encodeMillisecondsDate(_ date: Date, forKey key: Key) throws {
    try encode(Int64((date.timeIntervalSince1970 * 1000).rounded()), forKey: key)
  }

  mutating func encodeIfPresentMillisecondsDate(_ date: Date?, forKey key: Key) throws {
    guard let date else {
      return
    }
    try encodeMillisecondsDate(date, forKey: key)
  }
}
`;
}

function emitEnum(decl: SwiftEnum): string {
  const lines = [
    GENERATED_HEADER,
    'import Foundation',
    '',
    `public enum ${decl.name}: Codable, Equatable, Sendable {`,
    ...decl.cases.map(item => `  case ${item.name}`),
    '  case unknown(String)',
    '',
    '  public init(from decoder: Decoder) throws {',
    '    let container = try decoder.singleValueContainer()',
    '    let value = try container.decode(String.self)',
    '    switch value {',
    ...decl.cases.map(item => `    case "${escapeSwiftString(item.raw)}":\n      self = .${item.name}`),
    '    default:\n      self = .unknown(value)',
    '    }',
    '  }',
    '',
    '  public func encode(to encoder: Encoder) throws {',
    '    var container = encoder.singleValueContainer()',
    '    switch self {',
    ...decl.cases.map(item => `    case .${item.name}:\n      try container.encode("${escapeSwiftString(item.raw)}")`),
    '    case .unknown(let value):\n      try container.encode(value)',
    '    }',
    '  }',
    '}',
    '',
  ];
  return lines.join('\n');
}

function escapeSwiftString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function emitDecode(property: SwiftProperty): string {
  const key = `.${property.name}`;
  const optional = isOptionalRef(property.type);
  if (property.isDate) {
    return optional
      ? `    self.${property.name} = try container.decodeIfPresentMillisecondsDate(forKey: ${key})`
      : `    self.${property.name} = try container.decodeMillisecondsDate(forKey: ${key})`;
  }
  const typeName = emitRef(optional && property.type.kind === 'optional' ? property.type.of : property.type);
  return optional
    ? `    self.${property.name} = try container.decodeIfPresent(${typeName}.self, forKey: ${key})`
    : `    self.${property.name} = try container.decode(${typeName}.self, forKey: ${key})`;
}

function emitEncode(property: SwiftProperty): string {
  const key = `.${property.name}`;
  const optional = isOptionalRef(property.type);
  if (property.isDate) {
    return optional
      ? `    try container.encodeIfPresentMillisecondsDate(${property.name}, forKey: ${key})`
      : `    try container.encodeMillisecondsDate(${property.name}, forKey: ${key})`;
  }
  return optional
    ? `    try container.encodeIfPresent(${property.name}, forKey: ${key})`
    : `    try container.encode(${property.name}, forKey: ${key})`;
}

function emitStruct(decl: SwiftStruct): string {
  const conformances = ['Codable', 'Equatable', 'Sendable'];
  if (decl.identifiable) {
    conformances.push('Identifiable');
  }
  const needsCustomCodable = decl.properties.some(property => property.isDate);
  const initParams = decl.properties.map(property => `    ${property.name}: ${emitRef(property.type)}`);
  const initBody = decl.properties.map(property => `    self.${property.name} = ${property.name}`);
  const codingKeys = decl.properties.map(property => {
    const caseName = property.name.replace(/`/g, '');
    return caseName === property.wireName
      ? `    case ${property.name}`
      : `    case ${property.name} = "${escapeSwiftString(property.wireName)}"`;
  });
  const lines = [
    GENERATED_HEADER,
    'import Foundation',
    '',
    `public struct ${decl.name}: ${conformances.join(', ')} {`,
    ...decl.properties.map(property => `  public var ${property.name}: ${emitRef(property.type)}`),
    '',
    '  public init(',
    initParams.join(',\n'),
    '  ) {',
    ...initBody,
    '  }',
  ];
  if (decl.properties.length > 0) {
    lines.push('', '  public enum CodingKeys: String, CodingKey {', ...codingKeys, '  }');
  }
  if (needsCustomCodable) {
    lines.push(
      '',
      '  public init(from decoder: Decoder) throws {',
      '    let container = try decoder.container(keyedBy: CodingKeys.self)',
      ...decl.properties.map(emitDecode),
      '  }',
      '',
      '  public func encode(to encoder: Encoder) throws {',
      '    var container = encoder.container(keyedBy: CodingKeys.self)',
      ...decl.properties.map(emitEncode),
      '  }',
    );
  }
  lines.push('}', '');
  return lines.join('\n');
}

function emitDecl(decl: SwiftDecl): string {
  return decl.kind === 'enum' ? emitEnum(decl) : emitStruct(decl);
}

function unwrapPromise(checker: ts.TypeChecker, type: ts.Type): ts.Type | undefined {
  const symbolName = type.aliasSymbol?.getName() ?? type.getSymbol()?.getName();
  if (symbolName === 'Promise' || symbolName === 'PromiseLike') {
    return checker.getTypeArguments(type as ts.TypeReference)[0];
  }
  return undefined;
}

function isOptionalSymbol(symbol: ts.Symbol): boolean {
  if ((symbol.flags & ts.SymbolFlags.Optional) !== 0) {
    return true;
  }
  const declaration = symbol.valueDeclaration;
  return Boolean(declaration && ts.isParameter(declaration) && (declaration.questionToken || declaration.initializer));
}

function typeHasFunction(checker: ts.TypeChecker, type: ts.Type): boolean {
  if (isFunctionType(checker, type)) {
    return true;
  }
  const { parts } = decomposeUnion(type);
  return parts.some(part => isFunctionType(checker, part));
}

function typeHasDom(type: ts.Type): boolean {
  if (isDomType(type)) {
    return true;
  }
  const { parts } = decomposeUnion(type);
  return parts.some(isDomType);
}

function pickCallSignature(checker: ts.TypeChecker, type: ts.Type): ts.Signature | undefined {
  const signatures = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
  const usable = signatures.filter(signature => {
    if (!unwrapPromise(checker, signature.getReturnType())) {
      return false;
    }
    return signature.getParameters().every(parameter => {
      const declaration = parameter.valueDeclaration ?? parameter.declarations?.[0];
      const paramType = declaration
        ? checker.getTypeOfSymbolAtLocation(parameter, declaration)
        : checker.getTypeOfSymbol(parameter);
      return !typeHasFunction(checker, paramType) && !typeHasDom(paramType);
    });
  });
  return usable[0];
}

function typeHasAppearance(type: ts.Type): boolean {
  return Boolean(type.getProperty('appearance'));
}

function dropSkippedParam(type: ts.Type): boolean {
  const candidates = [type, ...decomposeUnion(type).parts];
  return candidates.some(part => {
    const name = declaredName(part);
    if (name && isSkippedUiName(name)) {
      return true;
    }
    return typeHasAppearance(part);
  });
}

function collectMethodFacades(
  program: ts.Program,
  modelNames: Set<string>,
  roots: readonly string[] = SWIFT_METHOD_ROOTS,
): { facades: SwiftMethodFacade[]; paramDecls: SwiftDecl[] } {
  const checker = program.getTypeChecker();
  const ctx: Ctx = {
    checker,
    decls: new Map(),
    queued: new Map(),
    usedNames: new Set(['JSONValue', ...modelNames]),
    typeIds: new Map(),
    modelNames,
  };
  const facades: SwiftMethodFacade[] = [];

  for (const root of roots) {
    const type = findDeclaredType(program, root);
    const owner = methodOwnerName(root);
    const methods: SwiftMethod[] = [];
    const seen = new Set<string>();

    for (const symbol of type.getProperties()) {
      const jsName = symbol.getName();
      if (seen.has(jsName) || shouldSkipMethodName(jsName)) {
        continue;
      }
      seen.add(jsName);
      const declaration = symbol.valueDeclaration ?? symbol.declarations?.[0];
      const propType = declaration
        ? checker.getTypeOfSymbolAtLocation(symbol, declaration)
        : checker.getTypeOfSymbol(symbol);
      const signature = pickCallSignature(checker, propType);
      if (!signature) {
        continue;
      }

      const params: SwiftMethodParam[] = [];
      let skippedRequired = false;
      for (const parameter of signature.getParameters()) {
        const paramDeclaration = parameter.valueDeclaration ?? parameter.declarations?.[0];
        const paramType = paramDeclaration
          ? checker.getTypeOfSymbolAtLocation(parameter, paramDeclaration)
          : checker.getTypeOfSymbol(parameter);
        const optional = isOptionalSymbol(parameter) || decomposeUnion(paramType).optional;
        if (dropSkippedParam(paramType)) {
          if (!optional) {
            skippedRequired = true;
          }
          continue;
        }
        const hint = `${owner}${pascalCase(jsName)}${pascalCase(parameter.getName())}`;
        params.push({
          name: swiftIdent(parameter.getName()),
          type: resolveRef(ctx, paramType, hint),
          optional,
        });
      }
      if (skippedRequired) {
        continue;
      }

      const promised = unwrapPromise(checker, signature.getReturnType());
      if (!promised) {
        continue;
      }
      const { parts, optional } = decomposeUnion(promised);
      const unique = uniqueTypes(parts, checker);
      const returnType =
        unique.length === 0 || unique.every(part => isNullish(part) || isNever(part))
          ? undefined
          : optional
            ? optionalize(resolveUnionParts(ctx, unique, `${owner}${pascalCase(jsName)}Result`))
            : resolveUnionParts(ctx, unique, `${owner}${pascalCase(jsName)}Result`);

      methods.push({ jsName, params, returnType });
    }

    methods.sort((a, b) => a.jsName.localeCompare(b.jsName));
    facades.push({ owner, methods });
  }

  drainQueue(ctx);
  const paramDecls = [...ctx.decls.values()]
    .filter(decl => !modelNames.has(decl.name))
    .sort((a, b) => a.name.localeCompare(b.name));
  facades.sort((a, b) => a.owner.localeCompare(b.owner));
  return { facades, paramDecls };
}

function emitMethodSignature(method: SwiftMethod): string {
  const params = method.params.map((param, index) => {
    const typeName = emitRef(param.optional ? optionalize(param.type) : param.type);
    const label = index === 0 ? '_ ' : '';
    return `${label}${param.name}: ${typeName}`;
  });
  const returns = method.returnType ? ` -> ${emitRef(method.returnType)}` : '';
  return `  func ${swiftIdent(method.jsName)}(${params.join(', ')}) async throws${returns}`;
}

function emitFacadeFile(facade: SwiftMethodFacade): string {
  const enumCases = facade.methods.map(
    method => `  case ${swiftIdent(method.jsName)} = "${escapeSwiftString(method.jsName)}"`,
  );
  const lines = [
    GENERATED_HEADER,
    'import Foundation',
    '',
    `/// Headless JS methods on \`${facade.owner}\`. Wire each raw value to ClerkJSRuntime.call.`,
    `public enum ${facade.owner}JSMethod: String, Sendable {`,
    ...enumCases,
    '}',
    '',
    `public protocol ${facade.owner}Methods: Sendable {`,
    ...facade.methods.map(emitMethodSignature),
    '}',
    '',
  ];
  return lines.join('\n');
}

function emitMethodFiles(facades: SwiftMethodFacade[], paramDecls: SwiftDecl[]): GeneratedSwiftFile[] {
  return [
    ...facades.map(facade => ({
      filename: `methods/${facade.owner}Methods.swift`,
      contents: emitFacadeFile(facade),
    })),
    ...paramDecls.map(decl => ({
      filename: `methods/${decl.name}.swift`,
      contents: emitDecl(decl),
    })),
  ];
}

export function generateSwiftModels(
  roots: readonly string[] = SWIFT_MODEL_ROOTS,
  methodRoots: readonly string[] = SWIFT_METHOD_ROOTS,
): GeneratedSwiftFile[] {
  const program = createSharedProgram();
  const decls = collectDecls(roots, program);
  const modelNames = new Set(decls.map(decl => decl.name));
  const { facades, paramDecls } = collectMethodFacades(program, modelNames, methodRoots);
  const files = [
    { filename: 'JSONValue.swift', contents: emitHelperFile() },
    ...decls.map(decl => ({ filename: `${decl.name}.swift`, contents: emitDecl(decl) })),
    ...emitMethodFiles(facades, paramDecls),
  ];
  return files.sort((a, b) => a.filename.localeCompare(b.filename));
}

function removeGeneratedSwift(dir: string): void {
  if (!fs.existsSync(dir)) {
    return;
  }
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      removeGeneratedSwift(full);
      fs.rmdirSync(full);
    } else if (entry.name.endsWith('.swift')) {
      fs.unlinkSync(full);
    }
  }
}

export function writeSwiftModels(
  outDir: string = defaultSwiftOutputDir(),
  files: GeneratedSwiftFile[] = generateSwiftModels(),
): GeneratedSwiftFile[] {
  fs.mkdirSync(outDir, { recursive: true });
  removeGeneratedSwift(outDir);
  for (const file of files) {
    const dest = path.join(outDir, file.filename);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, file.contents);
  }
  return files;
}

function isMainModule(): boolean {
  const entry = process.argv[1];
  return Boolean(entry && path.basename(entry).startsWith('generate-swift-models'));
}

if (isMainModule()) {
  const outDir = process.argv[2] ? path.resolve(process.argv[2]) : defaultSwiftOutputDir();
  const files = writeSwiftModels(outDir);
  process.stdout.write(`Wrote ${files.length} Swift files to ${outDir}\n`);
}
