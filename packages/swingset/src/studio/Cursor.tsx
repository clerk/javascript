import type { ReactNode } from 'react';

export type CursorKind = 'default' | 'pointer' | 'grab' | 'grabbing' | 'text' | 'not-allowed' | 'progress';

export interface CursorState {
  kind: CursorKind;
  visible: boolean;
  pressed: boolean;
}

export function cursorKindOf(element: Element): CursorKind {
  const cursor = getComputedStyle(element).cursor;
  if (cursor === 'wait') {
    return 'progress';
  }
  return (
    (['pointer', 'grab', 'grabbing', 'text', 'not-allowed', 'progress'] as const).find(kind => kind === cursor) ??
    'default'
  );
}

