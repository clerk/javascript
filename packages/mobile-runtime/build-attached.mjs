import { build } from 'rolldown';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(directory, '../expo/src/generated/attached-core.js');
const result = await build({
  input: path.join(directory, 'src/attached-core.ts'),
  platform: 'neutral',
  write: false,
  output: { format: 'esm', codeSplitting: false, comments: false },
});
const chunk = result.output.find(item => item.type === 'chunk');
if (!chunk || result.output.length !== 1 || chunk.imports.length)
  throw new Error('The attached resource transport must be a single self-contained module.');
const code = '// Generated by packages/mobile-runtime/build-attached.mjs. Do not edit.\n' + chunk.code;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== code)
    throw new Error('Regenerate the Expo resource transport with pnpm --filter @clerk/mobile-runtime build:attached.');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, code);
}
