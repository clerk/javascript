import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const directory = path.dirname(fileURLToPath(import.meta.url));
const generated = path.resolve(directory, '../native-bindings/generated');
const bundle = fs.readFileSync(path.join(directory, 'dist/clerk-core.js'));
const contract = JSON.parse(fs.readFileSync(path.join(generated, 'manifest.json'), 'utf8'));
const manifest = {
  ...contract,
  bundleSHA256: createHash('sha256').update(bundle).digest('hex'),
  bundleBytes: bundle.length,
  runtime: { apple: 'JavaScriptCore (system)', android: 'quickjs-ng v0.15.1 fd0a0210b7be00957751871e7e01b8291268fc29' },
};
fs.writeFileSync(path.join(directory, 'dist/core-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
const targets = process.argv.slice(2);
if (targets.length !== 2) throw new Error('Usage: node pack.mjs IOS_REPOSITORY ANDROID_REPOSITORY');
for (const [index, target] of targets.entries()) {
  const root = path.resolve(target, 'NativeCore');
  const assets = path.join(root, 'Resources');
  fs.mkdirSync(assets, { recursive: true });
  fs.copyFileSync(path.join(directory, 'dist/clerk-core.js'), path.join(assets, 'clerk-core.js'));
  fs.copyFileSync(path.join(directory, 'dist/core-manifest.json'), path.join(assets, 'core-manifest.json'));
  fs.copyFileSync(
    path.join(generated, index === 0 ? 'GeneratedAPI.swift' : 'GeneratedAPI.kt'),
    path.join(root, index === 0 ? 'GeneratedAPI.swift' : 'GeneratedAPI.kt'),
  );
  fs.copyFileSync(
    path.join(generated, index === 0 ? 'swift-api.txt' : 'kotlin-api.txt'),
    path.join(root, 'public-api.txt'),
  );
  const constants =
    index === 0
      ? `// Generated by @clerk/mobile-runtime pack. Do not edit.\nimport Foundation\npublic enum BundledCore {\n  public static let sha256 = ${JSON.stringify(manifest.bundleSHA256)}\n  public static let coreRevision = ${JSON.stringify(manifest.coreRevision)}\n}\n`
      : `// Generated by @clerk/mobile-runtime pack. Do not edit.\npackage com.clerk.api\npublic object BundledCore {\n  public const val sha256: String = ${JSON.stringify(manifest.bundleSHA256)}\n  public const val coreRevision: String = ${JSON.stringify(manifest.coreRevision)}\n}\n`;
  fs.writeFileSync(path.join(root, index === 0 ? 'BundledCore.swift' : 'BundledCore.kt'), constants);
}
console.log(JSON.stringify(manifest, null, 2));
